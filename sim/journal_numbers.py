"""Writes ../paper/journal/model_numbers.tex and model_table.tex from
results/traffic_model.json (made by traffic_model.py), plus the closed-form
constants quoted in the analytical-model section of the journal paper."""
import json
import os
import statistics

from traffic_model import form_cache_misses, form_group_misses

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "paper", "journal")
tm = json.load(open(os.path.join(HERE, "results", "traffic_model.json")))

NAMES = {"restart": "Restart", "replay": "Replay", "cacheaware": "Cache-aware",
         "standby": "Standby", "lifetime": "Lifetime", "consolidate": "Consolidate",
         "wait": "Wait", "sticky": "Sticky", "nightshift_nowait": "NightShift, no wait",
         "nightshift": "NightShift"}
# Why the model is off for each family of policies (used for the worst case).
WHY = {
    "fixed": ("the drift balance treats every fallback as equally likely to land "
              "on a phone that has not drifted yet"),
    "pool": ("phones return to the idle pool in sets released by one pipeline, "
             "so the pool holds a more even mix of blocks than independent "
             "uniform draws and the model, which assumes (U), slightly "
             "overpredicts the misses"),
}
FAMILY = {p: ("fixed" if p in ("wait", "sticky", "nightshift_nowait", "nightshift")
              else "pool") for p in NAMES}

B = 16
q = 1 - 1 / B
macros = {}
errs = {k: abs(v["rel_err"]) * 100 for k, v in tm.items()}
worst = max(errs, key=errs.get)
wp, wn = worst.split("@")
macros["TMErrAbsMaxPct"] = f"{max(errs.values()):.0f}"
macros["TMErrAbsMeanPct"] = f"{statistics.mean(errs.values()):.1f}"
macros["TMErrWorstKey"] = f"{NAMES[wp]} at {int(wn):,} phones"
w = tm[worst]
if w["sim_form"] + w["sim_repair"] < 300:
    macros["TMErrWorstWhy"] = (f"downloads are rare (about {w['sim_form'] + w['sim_repair']:.0f} "
                               "per run), so a handful of events moves the relative error by "
                               "several points; among the busier policies the largest error is "
                               "for " + NAMES[max((k for k in tm if tm[k]['sim_form'] + tm[k]['sim_repair'] >= 300), key=errs.get).split('@')[0]]
                               + ", where " + WHY[FAMILY[max((k for k in tm if tm[k]['sim_form'] + tm[k]['sim_repair'] >= 300), key=errs.get).split('@')[0]]])
else:
    macros["TMErrWorstWhy"] = WHY[FAMILY[wp]]
macros["TMqSixteenPct"] = f"{q ** 16 * 100:.1f}"
macros["TMqFortyEightPct"] = f"{q ** 48 * 100:.1f}"
macros["TMFormPerfect"] = f"{B * q ** B:.1f}"
macros["TMFormGreedy"] = f"{form_group_misses(B, 0, False):.1f}"
n = 10
macros["TMFormCacheN"] = str(n)
macros["TMFormCacheFracPct"] = f"{form_cache_misses(n * B, n, B) / (n * B) * 100:.0f}"

with open(os.path.join(OUT, "model_numbers.tex"), "w") as f:
    f.write("% generated by sim/journal_numbers.py from sim/results/traffic_model.json\n")
    for k, v in macros.items():
        f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")

order = list(NAMES)
rows = sorted(tm.items(), key=lambda kv: (int(kv[0].split("@")[1]) != 1000,
                                          int(kv[0].split("@")[1]),
                                          order.index(kv[0].split("@")[0])))
lines = [r"\begin{table}[t]", r"\centering",
         r"\caption{Shard traffic predicted by the analytical model against the "
         r"simulator (GB of model blocks downloaded per million delivered tokens; "
         r"activations excluded). Downloads are split into those at pipeline "
         r"formation and those at repair or refill (counts per run, simulator / "
         r"model). Means over seeds.}",
         r"\label{tab:model}", r"\small",
         r"\resizebox{\linewidth}{!}{%", r"\begin{tabular}{llrrrrr}", r"\toprule",
         r"Policy & Phones & Sim. & Model & Error & Formation & Repair \\", r"\midrule"]
prev_n = None
for key, v in rows:
    p, nn = key.split("@")
    if prev_n is not None and nn != prev_n:
        lines.append(r"\midrule")
    prev_n = nn
    lines.append(f"{NAMES[p]} & {int(nn):,} & {v['sim']:.1f} & {v['model']:.1f} & "
                 f"{v['rel_err'] * 100:+.1f}\\% & {v['sim_form']:.0f} / {v['model_form']:.0f} & "
                 f"{v['sim_repair']:.0f} / {v['model_repair']:.0f} \\\\")
lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}"]
open(os.path.join(OUT, "model_table.tex"), "w").write("\n".join(lines) + "\n")
print(macros)
